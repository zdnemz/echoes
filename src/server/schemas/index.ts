import { z } from '@hono/zod-openapi'

/**
 * Shared Zod schemas — single source of truth for request validation and
 * OpenAPI response documentation. Reusable on the client for form validation.
 */

// ---------------------------------------------------------------- primitives
export const UuidSchema = z.uuid().openapi({ example: '123e4567-e89b-12d3-a456-426614174000' })
export const TimestampSchema = z.string().openapi({ format: 'date-time', example: '2026-09-12T08:30:00.000Z' })

export const MoodSchema = z.enum(['great', 'good', 'okay', 'low', 'rough']).openapi({
  description: 'Mood rating: great 😄, good 🙂, okay 😐, low 🙁, rough 😣',
  example: 'good',
})

export const TagsSchema = z
  .array(z.string().min(1).max(40))
  .max(20)
  .openapi({ example: ['gratitude', 'work'], description: 'Free-text tags, per user' })

// ---------------------------------------------------------------- pagination
export const PageQuerySchema = z.object({
  page: z.coerce.number().int().min(1).default(1).openapi({ example: 1, description: '1-based page number' }),
  limit: z.coerce.number().int().min(1).max(100).default(20).openapi({ example: 20 }),
})

export function PaginatedSchema<T extends z.ZodType>(item: T) {
  return z.object({
    data: z.array(item),
    pagination: z.object({
      page: z.number().int().openapi({ example: 1 }),
      limit: z.number().int().openapi({ example: 20 }),
      total: z.number().int().openapi({ example: 42, description: 'Total rows matching the query' }),
    }),
  })
}

