export const UpdateGroupSchema = z
  .object({
    name: z.string().min(1).max(80).optional().openapi({ example: 'Family & close friends' }),
    auto_accept: z.boolean().optional().openapi({
      example: false,
      description: 'When true, invite-link visitors join instantly; when false they file a join request for approval',
    }),
    webhook_url: z
      .union([z.string().url(), z.literal(''), z.null()])
      .optional()
      .transform((v) => (v === '' || v === undefined ? null : v))
      .refine((v: string | null) => v === null || /^https:\/\//i.test(v), {
        message: 'Webhook URLs must be https',
      })
      .openapi({
        example: 'https://discord.com/api/webhooks/123/xyz',
        description:
          'HTTPS webhook URL for notifications, or null/empty to disable. Private/internal hosts are rejected at send time.',
      }),
  })
  .strict()

